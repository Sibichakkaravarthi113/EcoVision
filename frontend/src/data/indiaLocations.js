export function getDistricts(stateName) {
  if (!stateName) return [];
  const stateObj = INDIA_LOCATIONS.states.find(s => s.name.toLowerCase() === stateName.toLowerCase());
  return stateObj ? stateObj.districts : [];
}

export function getCities(stateName, districtName) {
  if (!stateName || !districtName) return [];
  const districts = getDistricts(stateName);
  const districtObj = districts.find(d => d.name.toLowerCase() === districtName.toLowerCase());
  return districtObj ? districtObj.cities : [];
}

export function resolveCoordinates(cityName, stateName) {
  if (cityName && CITY_COORDINATES[cityName]) {
    return CITY_COORDINATES[cityName];
  }
  if (stateName && STATE_CENTERS[stateName]) {
    return STATE_CENTERS[stateName];
  }
  return [20.5937, 78.9629]; // Default India center
}
